import sys
sys.stdout.reconfigure(encoding="utf-8")
sys.stderr.reconfigure(encoding="utf-8")
# Знакомлюсь с пользователем, запрашиваю базовые параметры (имя и возраст).
# Попытку получить имя оставил как обычную строку
# Попытку получить возраст сделал в try/except
# Также проверяю чтобы возраст не был отрицательным
user_name = input("Здравствуйте! Пожалуйста, введите своё имя: ")
try:
    user_age = int(input("А теперь сообщите пожалуйста свой возраст: "))
    if user_age < 0:
        print("Возраст должен быть положительным числом")
except Exception:
    print("Вы ввели свой возраст неверно - это должно быть целое число")


# Тут я собираю уже необходимые для наших вычислений данные
# Так как и вес и рост необходимы для вычислений я использую try/except
# Также проверяю чтобы рост и вес не были отрицательными
print("Что ж, теперь давайте узнаем самое главное")
try:
    user_weight = float(input("Напишите пожалуйста свой вес в кг: "))
    if user_weight < 0:
        print("Вес должен быть положительным числом")
except Exception:
    print("Вес нужно записать как целое число или дробное через точку")

try:
    user_height = float(input("Напишите пожалуйста свой рост в метрах: "))
    if user_height < 0:
        print("Рост должен быть положительным числом")
except Exception:
    print("Рост нужно записать как дробное число через точку, в метрах")


# Высчитываю индекс массы тела и необходимое количество воды
# + создаю две константы:
# 1) WATER_ML_TO_L для перевода мл в литры
# 2) WATER_PER_KG для нужного количества воды на кг веса
# Индекс массы тела округляю до десятых, воду в литрах не округляю
# (там в любом случае получится дробь максимум с 3 знаками после запятой)
WATER_ML_TO_L = 1000
WATER_PER_KG = 30
bmi = round(user_weight / (user_height ** 2), 1)
water_ml = user_weight * WATER_PER_KG
water_needed = water_ml / WATER_ML_TO_L


# Вывожу отчёт используя f-строки
print(f"Отчёт для пользователя: {user_name} ({user_age} г.)")
print(f"Твой индекс массы тела: {bmi}")
print(f"Рекомендуемое количество воды в день: {water_needed} л. в день")
print("Расчет окончен. Будьте здоровы!")
